// Prevents additional console window on Windows in release, DO NOT REMOVE!!
#![cfg_attr(not(debug_assertions), windows_subsystem = "windows")]

use std::process::Command;
use std::fs;
use std::io::Write;
use tempfile::Builder;

#[tauri::command]
async fn convert_alien(file_data: Vec<u8>, input_ext: String, target_ext: String) -> Result<Vec<u8>, String> {
    // Determine the alien flag based on target extension
    let target_flag = match target_ext.as_str() {
        "rpm" => "-r",    // to rpm
        "deb" => "-d",    // to deb
        "slp" => "-s",    // to stampede
        "tgz" => "-t",    // to tgz
        "pkg" => "-p",    // to Solaris pkg
        _ => return Err(format!("Format cible non supporté par Alien: {}", target_ext))
    };

    // Create a temporary directory for safe execution
    let temp_dir = Builder::new().prefix("convertisseur-alien-").tempdir()
        .map_err(|e| format!("Erreur création dossier temporaire: {}", e))?;
    let dir_path = temp_dir.path();

    // The input file path
    let input_path = dir_path.join(format!("input.{}", input_ext));
    
    // Write the raw bytes coming from the web app into the temp file
    let mut file = fs::File::create(&input_path)
        .map_err(|e| format!("Erreur écriture fichier: {}", e))?;
    file.write_all(&file_data)
        .map_err(|e| format!("Erreur écriture données: {}", e))?;

    // Execute alien command
    let output = Command::new("alien")
        .current_dir(&dir_path)
        .arg(target_flag)
        .arg(&input_path)
        .output()
        .map_err(|e| format!("Erreur de lancement de 'alien': {}", e))?;

    let stdout_msg = String::from_utf8_lossy(&output.stdout);
    let stderr_msg = String::from_utf8_lossy(&output.stderr);
    
    println!("Alien STDOUT: {}", stdout_msg);
    println!("Alien STDERR: {}", stderr_msg);

    if !output.status.success() {
        return Err(format!("Alien a échoué: {}", stderr_msg));
    }

    // Alien creates the new file in the current directory (which is temp_dir here)
    // We need to find the generated file that matches our target extension
    let mut generated_file_path = None;
    for entry in fs::read_dir(&dir_path).map_err(|e| format!("Erreur lecture dossier: {}", e))? {
        let entry = entry.map_err(|e| format!("Erreur entrée fichier: {}", e))?;
        let path = entry.path();
        if let Some(ext) = path.extension() {
            if ext.to_string_lossy() == target_ext {
                generated_file_path = Some(path);
                break;
            }
        }
    }

    let final_path = generated_file_path.ok_or("Alien n'a pas généré le fichier attendu.")?;

    // Read the generated bytes to send back to the web frontend
    let output_data = fs::read(&final_path)
        .map_err(|e| format!("Erreur lecture résultat: {}", e))?;

    Ok(output_data)
}

fn main() {
  tauri::Builder::default()
    .plugin(tauri_plugin_dialog::init())
    .plugin(tauri_plugin_fs::init())
    .plugin(tauri_plugin_shell::init())
    .invoke_handler(tauri::generate_handler![convert_alien])
    .run(tauri::generate_context!())
    .expect("error while running tauri application");
}
